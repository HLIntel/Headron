def links() -> list[str]:
    return ["- " + " · ".join(f"[{value[0]}]({path})" for path, value in GUIDES.items())]


def guide(path: str, verbs: Callable[[], list[str]]) -> str:
    language, purpose, workflow, canonical = GUIDES[path]
    return "\n".join(
        [
            f"# Headron — {language}",
            "",
            "<!-- GENERATED by atlas.py index --write; do not edit. -->",
            "",
            purpose,
            "",
            workflow,
            "",
            canonical,
            "",
            "## Commands",
            "",
            *verbs(),
            "",
        ]
    )
